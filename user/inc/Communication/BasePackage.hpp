#ifndef BASE_PACKAGE_HPP
#define BASE_PACKAGE_HPP

/* Includes ------------------------------------------------------------------*/
#include <stdint.h>

/* Defines -------------------------------------------------------------------*/

/* Global variables ----------------------------------------------------------*/

// -----------------------------------------------------------------------------
namespace Packages{

    // -------------------------------------------------------------------------
    /* Класс для описания базового пакета информации
    *  Виртуальные функции закомментированы, чтобы не создавать vtable, тем не 
    *  менее эти методы необходимо реализовать в дочерних классах для 
    *  удобства работы.
    *  Для отправки посылки по интерфейсу связи нужен доступ только к data_ptr 
    *  и len, которые необходимо определить в дочернем классе.
    *  ---------------------------------------------------------------------- */
    class BasePackage{
    protected:
        /**
         * @brief   Первый байт заголовка пакета.
         * @details Общий для всех пакетов, отправляемых устройством. Объявлен
         *          как static constexpr поле базового класса — наследники
         *          используют его без квалификации при формировании заголовка.
         */
        static constexpr uint8_t HeaderFirstByte  = 0xC8;

        /**
         * @brief   Второй байт заголовка пакета.
         * @details См. HeaderFirstByte.
         */
        static constexpr uint8_t HeaderSecondByte = 0x8C;

    public:
        uint8_t *data_ptr;
        uint8_t len;

        BasePackage(): data_ptr(nullptr), len(0) {}
        ~BasePackage() = default;

    protected:
        /**
         * @brief   Вычисление контрольной суммы пакета.
         * @return  uint8_t   Сумма всех байтов пакета, кроме байта самой контрольной суммы.
         * @details Проходит по всем байтам data_ptr,
         *          накапливает сумму в 16-битной переменной и возвращает младший байт.
         */
        uint8_t CountControlSum(){
            uint16_t crc = 0;
            // Исключаем последний байт (собственно контрольную сумму)
            for (uint8_t i = 0; i < len - 1; i++){
                crc += data_ptr[i];
            }
            return static_cast<uint8_t>(crc);
        }   
    };

} // namespace Packages
#endif /*   BASE_PACKAGE_HPP   */